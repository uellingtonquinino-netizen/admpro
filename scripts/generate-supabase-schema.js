/* Gera o esquema PostgreSQL a partir do SQLite canônico após npm run build:main. */
const fs = require('fs')
const os = require('os')
const path = require('path')
const Database = require('better-sqlite3')
const migrations = require('../dist-main/database/migrations')
const temporaryDb = path.join(os.tmpdir(), `otimizzai-schema-${process.pid}.db`)
const output = path.join(__dirname, '..', 'supabase', 'migrations', '20260801000000_initial_schema.sql')

function postgresify(sql) {
  return sql
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bREAL\b/gi, 'NUMERIC')
    .replace(/datetime\('now'\)/gi, 'CURRENT_TIMESTAMP')
    .replace(/\s+COLLATE\s+NOCASE/gi, '')
}

function withSemicolon(sql) {
  const statement = postgresify(sql).trim()
  return statement.endsWith(';') ? statement : `${statement};`
}

function tableName(sql) {
  return /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?["`[]?([\w]+)/i.exec(sql)?.[1]
}

function referencedTables(sql) {
  return [...sql.matchAll(/REFERENCES\s+["`[]?([\w]+)/gi)].map(match => match[1])
}

function sortTables(tables) {
  const pending = new Map(tables.map(item => [tableName(item.sql), item]))
  const ordered = []
  while (pending.size) {
    const next = [...pending.values()].find(item =>
      referencedTables(item.sql).every(reference => !pending.has(reference))
    )
    // Em caso de referência circular, deixa a revisão explícita no SQL gerado.
    const item = next || pending.values().next().value
    ordered.push(item)
    pending.delete(tableName(item.sql))
  }
  return ordered
}

try {
  if (fs.existsSync(temporaryDb)) fs.unlinkSync(temporaryDb)
  const db = new Database(temporaryDb)
  migrations.runMigrations(db)
  const objects = db.prepare(`
    SELECT sql FROM sqlite_master WHERE type IN ('table', 'index')
    AND name NOT LIKE 'sqlite_%' AND name != 'migrations' AND sql IS NOT NULL
    ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, rowid
  `).all()
  db.close()
  const tables = sortTables(objects.filter(item => /^CREATE TABLE/i.test(item.sql)))
  const indexes = objects.filter(item => /^CREATE INDEX/i.test(item.sql))
  const sql = [
    '-- Gerado por scripts/generate-supabase-schema.js. Não editar manualmente.',
    '-- Fonte: src/main/database/migrations.ts',
    'create schema if not exists public;',
    ...tables.map(({ sql }) => withSemicolon(sql)),
    ...indexes.map(({ sql }) => withSemicolon(sql)),
    '',
  ].join('\n\n')
  fs.mkdirSync(path.dirname(output), { recursive: true })
  fs.writeFileSync(output, sql, 'utf8')
  console.log(`Migração criada em ${output}`)
} finally {
  if (fs.existsSync(temporaryDb)) fs.unlinkSync(temporaryDb)
}
